#!/usr/bin/env python3
"""Validate published partitions and, optionally, a locally generated input pickle."""
import argparse
import csv
import gzip
import hashlib
import json
import pickle
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def rows(path):
    with Path(path).open() as handle:
        return list(csv.DictReader(handle, delimiter='\t'))


def require(condition, message):
    if not condition:
        raise ValueError(message)


def read_split(path):
    labels = {}
    for line in Path(path).read_text().splitlines():
        sid, label = line.split()
        require(sid not in labels, f'Duplicate ID: {path}: {sid}')
        require(label in ('train', 'validation', 'test'), f'Invalid label: {path}')
        labels[sid] = label
    require(set(labels.values()) == {'train', 'validation', 'test'}, f'Empty subset: {path}')
    return labels


def validate_assets():
    manifest = json.loads((ROOT / 'metadata/checksums.json').read_text())
    for name, checksum in manifest.items():
        require(hashlib.sha256((ROOT / name).read_bytes()).hexdigest() == checksum,
                f'Published file changed: {name}')
    cohort = rows(ROOT / 'metadata/cohort.tsv')
    ids = {r['transcript_id_original'] for r in cohort}
    bases = {r['transcript_id_original']: r['transcript_id_base'] for r in cohort}
    genes = {r['transcript_id_original']: r['gene_id_base'] for r in cohort}
    clusters = defaultdict(dict)
    for r in rows(ROOT / 'metadata/protein_cluster_membership.tsv'):
        require(r['transcript_id'] not in clusters[r['threshold']], 'Duplicate cluster membership')
        clusters[r['threshold']][r['transcript_id']] = r['cluster_id']
    categories = defaultdict(set)
    for r in rows(ROOT / 'metadata/gene_go_slim_membership.tsv'):
        categories[r['go_slim_id'].replace(':', '_')].add(r['ensembl_gene_id'])
    count = 0
    for analysis, groups in [('protein_cluster_splits', ('c50', 'c70', 'c90')),
                             ('go_slim_holdout', sorted(categories))]:
        for group in groups:
            for seed in range(10):
                path = ROOT / 'splits' / analysis / group / f'seed_{seed}' / 'class.txt'
                labels = read_split(path)
                require(set(labels) <= ids, f'Unknown IDs: {path}')
                threshold = group if analysis == 'protein_cluster_splits' else 'c50'
                membership = clusters[threshold]
                if analysis == 'protein_cluster_splits':
                    require(set(labels) == ids, f'Incomplete partition: {path}')
                else:
                    test = {sid for sid in ids if genes[sid] in categories[group]}
                    blocked = {membership[bases[sid]] for sid in test}
                    excluded = {sid for sid in ids - test if membership[bases[sid]] in blocked}
                    require({sid for sid, label in labels.items() if label == 'test'} == test,
                            f'Incorrect functional test set: {path}')
                    require(set(labels) == ids - excluded, f'Incorrect c50 exclusion: {path}')
                seen = defaultdict(set)
                for sid, label in labels.items():
                    seen[membership[bases[sid]]].add(label)
                require(all(len(v) == 1 for v in seen.values()), f'Cluster leakage: {path}')
                count += 1
    mrna = {r['transcript_id']: r['cluster_id'] for r in rows(ROOT / 'metadata/mrna_cluster_membership.tsv')}
    require(set(mrna) == ids, 'mRNA cluster cohort mismatch')
    for seed in range(10):
        path = ROOT / 'splits/mrna_c80' / f'seed_{seed}' / 'class.txt'
        labels = read_split(path)
        require(set(labels) == ids, f'Incomplete mRNA partition: {path}')
        seen = defaultdict(set)
        for sid, label in labels.items():
            seen[mrna[sid]].add(label)
        require(all(len(v) == 1 for v in seen.values()), f'mRNA cluster leakage: {path}')
        count += 1
    print(f'PASS: {len(ids)} cohort IDs; {count} fixed splits; no cluster/function leakage.')
    return ids


def validate_input(path, strict_hashes=False):
    import numpy as np
    ref = json.loads((ROOT / 'metadata/input_reference.json').read_text())
    expected = {r['transcript_id_original'] for r in rows(ROOT / 'metadata/cohort.tsv')}
    # Load only trusted input files generated by the repository's preprocessing pipeline.
    with gzip.open(path, 'rb') as handle:
        data, tissues = pickle.load(handle)
    require(set(data) == expected, 'Input cohort does not match the published partitions')
    require(list(tissues) == ref['te_columns'], 'Input tissue names/order differ')
    shapes = {'oht': (11000, 6), 'TE': (78,), 'y_mask': (78,), 'emb_T5u': (1024,)}
    for sid, record in data.items():
        for key, shape in shapes.items():
            require(key in record and np.shape(record[key]) == shape, f'{sid}: invalid {key}')
        mask = np.asarray(record['y_mask'])
        require(np.isin(mask, [0, 1]).all(), f'{sid}: invalid target mask')
        require(np.isfinite(np.asarray(record['TE'])[mask == 0]).all(), f'{sid}: invalid observed TE')
        require(np.isfinite(record['emb_T5u']).all(), f'{sid}: invalid T5u embedding')
    if strict_hashes:
        for key in shapes:
            digest = hashlib.sha256()
            for sid in sorted(data):
                array = np.asarray(data[sid][key])
                for value in (sid, str(array.dtype), str(array.shape)):
                    digest.update(value.encode())
                digest.update(np.ascontiguousarray(array).tobytes())
            require(digest.hexdigest() == ref['key_content_sha256'][key],
                    f'{key}: differs from reference (dtype or generated values may differ)')
    print('PASS: input schema, cohort, tissues and masks' + ('; exact core hashes.' if strict_hashes else '.'))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input', type=Path)
    parser.add_argument('--strict-hashes', action='store_true')
    args = parser.parse_args()
    validate_assets()
    if args.input:
        validate_input(args.input, args.strict_hashes)
